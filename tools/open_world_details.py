def enrich(content):
    regions,people,quests=content['regions'],content['people'],content['quests']
    for i,row in enumerate(ERRANDS):
        title,region,scene,dest,premise,objective,kind=row
        giver=next(k for k,v in people.items() if v['region']==region and v['scene']==scene)
        quest=quests[f'errand_{i+1:02}']
        quest.update(name=title,region=region,scene=scene,giver=giver,text=premise)
        quest['steps']=[{'kind':'talk','region':region,'scene':scene,'npc':giver,'text':premise},
          {'kind':kind,'region':region,'scene':dest,'text':objective,'item':'草藥','count':1,'enemies':[f'enemy_{(i*11)%100+1:03}']},
          {'kind':'report','region':region,'scene':scene,'npc':giver,'text':f'回到{scene}，向委託人交代「{title}」的結果。'}]
    for pid,npc in people.items():
        if not pid.startswith('local_'):continue
        local=[q for q in quests.values() if q['giver']==pid]
        if local:
            npc['text']=local[0]['text']
            npc['reply']='我聽說的事有：'+'、'.join(q['name'] for q in local)+'。你若願意幫忙，就讓我們先把事情說清楚。'
        else:
            npc['text']=f"{npc['region']}的路都經過{npc['scene']}。"+npc['text']
            npc['reply']=f"在{npc['scene']}歇腳時，常聽人提起{regions[npc['region']][(regions[npc['region']].index(npc['scene'])+1)%len(regions[npc['region']])]}。沿路找人問問，比只看告示更有意思。"
    for i,weapon in enumerate(' '.join(WEAPONS).split()):content['enemies'][f'enemy_{i+1:03}']['weapon']=weapon
